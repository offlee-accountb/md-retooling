    spine = ET.SubElement(root, _q("opf", "spine"))
    ET.SubElement(spine, _q("opf", "itemref"), {"idref": "header", "linear": "yes"})
    ET.SubElement(spine, _q("opf", "itemref"), {"idref": "section0", "linear": "no"})

